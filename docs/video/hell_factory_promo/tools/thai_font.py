#!/usr/bin/env python3
"""The Thai face of the film, embedded: kit/thai.gen.ts.

  python tools/thai_font.py [FOLDER]      FOLDER holds Kanit-Regular.ttf and Kanit-Medium.ttf (default ~/Library/Fonts)

Geist has no Thai letters, so the Thai cut sets them in Kanit (Cadson Demak, SIL Open Font License 1.1). Only the Thai
block is kept, so every Latin letter, figure and mark still comes from Geist; Kanit Medium stands beside Geist 600 and
Kanit Regular beside Geist 400-500, which is where their weights match by eye. The file also holds each Thai letter's
advance width in ems, which the kit's `tw` and `mw` measure words by (a mark above or below a letter has none).
Needs fontTools.
"""
import base64, io, json, pathlib, sys
from fontTools import subset
from fontTools.ttLib import TTFont

HERE = pathlib.Path(__file__).resolve().parent.parent
SRC = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path.home() / "Library/Fonts"
THAI = list(range(0x0E01, 0x0E3B)) + list(range(0x0E3F, 0x0E5C))
out, adv = [], {}
for key, name, file in (("r", "THAI_R", "Kanit-Regular.ttf"), ("m", "THAI_M", "Kanit-Medium.ttf")):
    if not (SRC / file).is_file():
        raise SystemExit(f"no {file} in {SRC}: give the folder that holds Kanit's .ttf files")
    font = TTFont(SRC / file)
    opt = subset.Options(layout_features=["*"], name_IDs=[0, 1, 2, 3, 4, 5, 6, 13, 14], notdef_outline=True)
    s = subset.Subsetter(opt); s.populate(unicodes=THAI + [0x200B, 0x25CC]); s.subset(font)
    cm, hm, em = font.getBestCmap(), font["hmtx"].metrics, font["head"].unitsPerEm
    adv[key] = {chr(c): round(hm[cm[c]][0] / em, 4) for c in THAI if c in cm}
    buf = io.BytesIO(); font.save(buf)
    out.append(f'export const {name} = "data:font/ttf;base64,{base64.b64encode(buf.getvalue()).decode()}";')
    print(f"{file}: {len(adv[key])} Thai letters, {len(buf.getvalue()) // 1024} KB embedded; {font['name'].getDebugName(0)}")
dest = HERE / "kit" / "thai.gen.ts"
dest.write_text("// generated by tools/thai_font.py: Kanit's Thai block (Cadson Demak, SIL Open Font License 1.1), embedded, and its advance widths in ems\n"
                + "\n".join(out) + "\nexport const TADV: Record<string, Record<string, number>> = " + json.dumps(adv, ensure_ascii=False) + ";\n", encoding="utf-8", newline="\n")
print(dest)
